/**
 * Whisper Subtitle Post-Processing & Normalization
 *
 * Implements:
 * 1. RapidFuzz-style fuzzy spelling correction for character names in English transcripts.
 *    - Conservative similarity threshold (>= 86% ratio, Levenshtein distance <= 2).
 *    - Whole-word matching only with case awareness.
 *    - Never replaces common English words from the dictionary/stoplist.
 *    - Logs every replacement with segment ID / timing for review.
 * 2. Hallucination filtering for silence/music loops ("Thank you for watching", "Subtitles by...").
 * 3. Re-engineered `mergeIsolatedSingleWords`:
 *    - Guarantees at most 2 rows (`max_line_count: 2`) via smart line balancing.
 *    - Never creates a 3rd line.
 *    - Handles mid-sentence lowercasing and start-of-cue uppercasing properly.
 */

export interface CueBlock {
  start: string;
  end: string;
  startMs: number;
  endMs: number;
  text: string;
}


/**
 * Standard silence/music hallucination phrases generated by Whisper on non-speech segments.
 */
export const DEFAULT_HALLUCINATIONS: RegExp[] = [
  /^\s*(?:thank\s+you\s+(?:for\s+watching|very\s+much)?|thanks\s+for\s+watching)[.!]?\s*$/i,
  /^\s*please\s+subscribe(?:\s+to\s+(?:my|our)\s+channel)?[.!]?\s*$/i,
  /^\s*(?:like\s+and\s+subscribe|subscribe\s+and\s+like)[.!]?\s*$/i,
  /^\s*(?:subtitles?\s+by|transcribed\s+by|translated\s+by|captioned\s+by|sync\s+by)\b.*$/i,
  /^\s*(?:amara\.org|subtitlestools\.com|opensubtitles|addic7ed)\b/i,
  /^\s*(?:watching|watching\.|bye\.|see\s+you\s+next\s+time[.]?)\s*$/i,
  /^\s*(?:mbc|nhk|tbs|tv\s+tokyo)\s*$/i,
];

/**
 * Computes Levenshtein distance between two strings.
 */
export function levenshteinDistance(a: string, b: string): number {
  const m = a.length;
  const n = b.length;
  if (m === 0) return n;
  if (n === 0) return m;

  const dp: number[] = new Array(n + 1);
  for (let j = 0; j <= n; j++) dp[j] = j;

  for (let i = 1; i <= m; i++) {
    let prev = dp[0];
    dp[0] = i;
    const charA = a.charCodeAt(i - 1);
    for (let j = 1; j <= n; j++) {
      const temp = dp[j];
      const cost = charA === b.charCodeAt(j - 1) ? 0 : 1;
      dp[j] = Math.min(dp[j] + 1, dp[j - 1] + 1, prev + cost);
      prev = temp;
    }
  }

  return dp[n];
}

/**
 * Computes RapidFuzz-style similarity ratio (0 to 100):
 * ratio = ((lenA + lenB - distance) / (lenA + lenB)) * 100
 */
export function similarityRatio(a: string, b: string): number {
  const lenA = a.length;
  const lenB = b.length;
  if (lenA === 0 && lenB === 0) return 100;
  if (lenA === 0 || lenB === 0) return 0;

  const dist = levenshteinDistance(a.toLowerCase(), b.toLowerCase());
  return Math.round(((lenA + lenB - dist) / (lenA + lenB)) * 100);
}

/**
 * Corrects near-miss spellings of character names in a subtitle string.
 *
 * Requirements:
 * - Full character name list used (unconstrained by token budget).
 * - Conservative similarity threshold (>= 86% ratio, edit distance <= 2).
 * - Whole-word matching only (`\bWORD\b`).
 * - Case-aware: only candidate words that are capitalized in transcript are considered.
 * - Never replaces common English words from the dictionary stoplist.
 * - Minimum word length >= 4 characters to avoid false short-word collisions.
 * - Logs every replacement (original -> corrected, similarity).
 */
export function correctCharacterSpellings(
  text: string,
  characterNames: string[],
  segmentId?: number | string,
  onReplace?: (original: string, corrected: string, similarity: number, segmentId?: number | string) => void
): string {
  if (!text || !characterNames || characterNames.length === 0) return text;

  // Build target candidate names (both full names and individual name components of >= 4 chars)
  interface TargetName {
    clean: string;
    isMultiWord: boolean;
  }
  const targets: TargetName[] = [];
  const seenTargets = new Set<string>();

  for (const raw of characterNames) {
    const trimmed = raw.trim();
    if (!trimmed) continue;
    if (!seenTargets.has(trimmed.toLowerCase())) {
      seenTargets.add(trimmed.toLowerCase());
      targets.push({ clean: trimmed, isMultiWord: trimmed.includes(' ') });
    }
    // Also include individual tokens if multi-word (e.g. "Haruhi" and "Suzumiya" from "Haruhi Suzumiya")
    if (trimmed.includes(' ')) {
      for (const part of trimmed.split(/\s+/)) {
        if (part.length >= 4 && !seenTargets.has(part.toLowerCase()) && !COMMON_ENGLISH_WORDS.has(part.toLowerCase())) {
          seenTargets.add(part.toLowerCase());
          targets.push({ clean: part, isMultiWord: false });
        }
      }
    }
  }

  // Tokenize text into words preserving surrounding punctuation and whitespace
  return text.replace(/\b([A-Z][a-zA-Z'-]{3,})\b/g, (match, word: string) => {
    const lowerWord = word.toLowerCase();

    // Invariant: Never replace common English words
    if (COMMON_ENGLISH_WORDS.has(lowerWord)) {
      return match;
    }

    let bestMatch: string | null = null;
    let highestSim = 0;

    for (const target of targets) {
      if (target.isMultiWord) continue; // single-word regex matches single words
      const targetClean = target.clean;
      if (targetClean.length < 4) continue;

      // Exact match (case insensitive) -> preserve proper target casing
      if (lowerWord === targetClean.toLowerCase()) {
        if (word !== targetClean) {
          bestMatch = targetClean;
          highestSim = 100;
          break;
        }
        return match; // already exact
      }

      // Length difference must be at most 2 chars
      if (Math.abs(word.length - targetClean.length) > 2) continue;

      const dist = levenshteinDistance(lowerWord, targetClean.toLowerCase());
      // Strict edit distance limit
      if (dist > 2) continue;

      const sim = similarityRatio(word, targetClean);
      // Conservative similarity threshold
      if (sim >= 86 && sim > highestSim) {
        highestSim = sim;
        bestMatch = targetClean;
      }
    }

    if (bestMatch && bestMatch !== word) {
      if (onReplace) {
        onReplace(word, bestMatch, highestSim, segmentId);
      }
      return bestMatch;
    }

    return match;
  });
}

/**
 * Filters out subtitle cues that match known silence/music hallucinations or repetitive loops.
 */
export function filterHallucinations(
  cues: CueBlock[],
  customPatterns?: string[]
): CueBlock[] {
  const extraRegexes: RegExp[] = (customPatterns || []).map((pat) => new RegExp(pat, 'i'));
  const allPatterns = [...DEFAULT_HALLUCINATIONS, ...extraRegexes];

  return cues.filter((cue) => {
    const cleanText = cue.text.replace(/[\n\r]+/g, ' ').trim();
    if (!cleanText) return false;

    // Check known hallucination patterns
    for (const pat of allPatterns) {
      if (pat.test(cleanText)) {
        return false;
      }
    }

    // Check for repetitive loops (e.g. "Thank you. Thank you. Thank you." or the exact same phrase repeated 3+ times)
    const words = cleanText.split(/\s+/);
    if (words.length >= 6) {
      const firstTwo = words.slice(0, 2).join(' ').toLowerCase();
      const occurrences = cleanText.toLowerCase().split(firstTwo).length - 1;
      if (occurrences >= 3) {
        return false;
      }
    }

    return true;
  });
}

/**
 * Formats subtitle text into at most 2 balanced lines of maxLineWidth.
 * Returns ok: false if the text cannot fit within 2 lines of maxLineWidth without overflowing.
 */
export function balanceSubtitleLines(
  text: string,
  maxLineWidth: number = 44
): { lines: string[]; ok: boolean } {
  // Normalize whitespace and collapse existing newlines into single spaces for re-balancing
  const clean = text.replace(/[\n\r]+/g, ' ').replace(/\s+/g, ' ').trim();
  if (!clean) return { lines: [], ok: true };

  // Fits on a single line cleanly
  if (clean.length <= maxLineWidth) {
    return { lines: [clean], ok: true };
  }

  // If text is longer than 2 full lines, it cannot fit in at most 2 lines without creating a 3rd row
  if (clean.length > maxLineWidth * 2) {
    return { lines: [clean], ok: false };
  }

  // Find ideal split point near the middle (length / 2)
  const mid = Math.floor(clean.length / 2);
  const words = clean.split(' ');

  let bestIndex = -1;
  let bestScore = Infinity;
  let currentLen = 0;

  for (let i = 0; i < words.length - 1; i++) {
    currentLen += words[i].length + (i > 0 ? 1 : 0);
    const line1Len = currentLen;
    const line2Len = clean.length - line1Len - 1;

    // Both lines must be within maxLineWidth
    if (line1Len <= maxLineWidth && line2Len <= maxLineWidth) {
      // Prioritize natural punctuation breaks (comma, semicolon, period)
      const endsWithPunct = /[,;:.!?]$/.test(words[i]);
      const diffFromMid = Math.abs(line1Len - mid);
      const score = diffFromMid - (endsWithPunct ? 12 : 0);

      if (score < bestScore) {
        bestScore = score;
        bestIndex = i;
      }
    }
  }

  if (bestIndex !== -1) {
    const line1 = words.slice(0, bestIndex + 1).join(' ');
    const line2 = words.slice(bestIndex + 1).join(' ');
    return { lines: [line1, line2], ok: true };
  }

  // Cannot balance into 2 lines <= maxLineWidth
  return { lines: [clean], ok: false };
}

/**
 * Merges isolated single-word subtitle cues into adjacent cues.
 *
 * Fixes:
 * 1. Strict 2-row guarantee (`max_line_count: 2`): never creates a 3rd row!
 *    Re-balances lines using `balanceSubtitleLines`. If the merged text would require 3 lines,
 *    the merge is skipped and original cues are kept separate.
 * 2. Proper capitalization:
 *    - Appending mid-sentence: lowercases the isolated word UNLESS it is a character name, proper noun, "I", or acronym.
 *    - Prepending to next cue: capitalizes the isolated word and lowercases the next word (unless proper noun).
 * 3. Accurate sentence boundary detection.
 */
export function mergeIsolatedSingleWords(
  cues: CueBlock[],
  maxLineWidth: number = 44,
  maxLineCount: number = 2,
  characterNames?: string[]
): CueBlock[] {
  if (cues.length <= 1) return cues;

  const charNameSet = new Set<string>();
  for (const name of characterNames || []) {
    for (const part of name.split(/\s+/)) {
      if (part.length >= 2) charNameSet.add(part.toLowerCase());
    }
  }

  const merged: CueBlock[] = [];

  for (let i = 0; i < cues.length; i++) {
    const cur = cues[i];
    const words = cur.text.trim().split(/\s+/);
    const isSingleWord = words.length === 1 && cur.text.length < 22;

    // Sound effects or parenthesized cues like "(groans)" / "[sighs]" are not spoken dialogue words
    const isParenthesized = /^[([].*[)\]]$/.test(cur.text.trim());
    if (isParenthesized) {
      merged.push(cur);
      continue;
    }

    if (isSingleWord) {
      const curEndsSentence = /[.!?…]["'”’]?\s*$/.test(cur.text.trim());

      // Helper: lowercases a word if it's not "I", a character name, or an acronym
      const fixMidSentenceWord = (w: string): string => {
        const cleanW = w.replace(/^[^\w]+|[^\w]+$/g, '');
        if (/^I(?:['’](?:m|ll|ve|d))?$/i.test(cleanW)) {
          return w.replace(/^i/i, 'I');
        }
        // Acronyms (e.g. "FBI", "USA", "TV") keep uppercase
        if (/^[A-Z]{2,}$/.test(cleanW)) {
          return w;
        }
        // Known character name / proper noun: preserve uppercase
        if (charNameSet.has(cleanW.toLowerCase())) {
          return w;
        }
        // Lowercase initial letter for ordinary words
        return w.charAt(0).toLowerCase() + w.slice(1);
      };

      // Helper: capitalizes the first letter of a word/phrase
      const fixStartSentenceWord = (w: string): string => {
        return w.charAt(0).toUpperCase() + w.slice(1);
      };

      // Priority 1: If cur does NOT end sentence and next cue is very close (< 500ms),
      // try prepending to next cue
      if (i + 1 < cues.length && !curEndsSentence) {
        const next = cues[i + 1];
        const gap = next.startMs - cur.endMs;

        if (gap >= 0 && gap < 500) {
          const cleanCur = fixStartSentenceWord(cur.text.trim());
          // In next cue, lower-case its first word since it now continues cur's thought
          const nextLines = next.text.trim().split(/\s+/);
          if (nextLines.length > 0) {
            nextLines[0] = fixMidSentenceWord(nextLines[0]);
          }
          const cleanNext = nextLines.join(' ');
          const combinedCandidate = `${cleanCur} ${cleanNext}`;

          const balanced = balanceSubtitleLines(combinedCandidate, maxLineWidth);
          if (balanced.ok && balanced.lines.length <= maxLineCount) {
            next.text = balanced.lines.join('\n');
            next.start = cur.start;
            next.startMs = cur.startMs;
            continue; // successfully merged into next
          }
        }
      }

      // Priority 2: Try appending to previous cue
      if (merged.length > 0) {
        const prev = merged[merged.length - 1];
        const gap = cur.startMs - prev.endMs;
        const prevEndsSentence = /[.!?…]["'”’]?\s*$/.test(prev.text.trim());

        if (gap >= 0 && gap < 450 && !prevEndsSentence) {
          // Mid-sentence append: lowercase the isolated word if not a character name/proper noun
          const cleanCur = fixMidSentenceWord(cur.text.trim());
          const cleanPrev = prev.text.replace(/[\n\r]+/g, ' ').trim();
          const combinedCandidate = `${cleanPrev} ${cleanCur}`;

          const balanced = balanceSubtitleLines(combinedCandidate, maxLineWidth);
          if (balanced.ok && balanced.lines.length <= maxLineCount) {
            prev.text = balanced.lines.join('\n');
            prev.end = cur.end;
            prev.endMs = cur.endMs;
            continue; // successfully merged into prev
          }
        }
      }
    }

    merged.push(cur);
  }

  return merged;
}
